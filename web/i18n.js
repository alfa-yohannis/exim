/** The interface language: which one is active, its texts, and the switch between them. */
class InterfaceLanguage {
  /** Browser-storage key for the chosen language. */
  static STORAGE_KEY = 'exim-rag.language';

  /**
   * Offered languages, in switcher order, with the locale used for numbers
   * and dates and the flag shown beside the code.
   */
  static CHOICES = [
    { code: 'id', label: 'ID', name: 'Bahasa Indonesia', locale: 'id-ID', flag: 'Indonesia' },
    { code: 'en', label: 'EN', name: 'English', locale: 'en-GB', flag: 'United Kingdom' },
    { code: 'vi', label: 'VI', name: 'Tiếng Việt', locale: 'vi-VN', flag: 'Vietnam' },
  ];

  constructor(texts) {
    this.texts = texts;
    this.code = this.#initialCode();
  }

  /** The locale for formatting numbers and dates in the active language. */
  get locale() {
    return InterfaceLanguage.CHOICES.find((choice) => choice.code === this.code).locale;
  }

  /** Returns the text for `key`, with `{name}` placeholders filled from `values`. */
  t(key, values = {}) {
    const text = this.texts[this.code][key] ?? this.texts.id[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (placeholder, name) =>
      (name in values ? String(values[name]) : placeholder));
  }

  /** The display name of a top-level corpus folder, which is a country. */
  countryName(folderName) {
    const key = `country.${folderName}`;
    return key in this.texts.id ? this.t(key) : folderName;
  }

  /** Writes the active language's text into every marked element under `root`. */
  apply(root = document) {
    document.documentElement.lang = this.code;
    for (const element of root.querySelectorAll('[data-i18n]')) {
      element.textContent = this.t(element.dataset.i18n);
    }
    // Only the fixed texts above are written this way, never page content.
    for (const element of root.querySelectorAll('[data-i18n-html]')) {
      element.innerHTML = this.t(element.dataset.i18nHtml);
    }
    for (const element of root.querySelectorAll('[data-i18n-attr]')) {
      for (const pair of element.dataset.i18nAttr.split(';')) {
        const [attribute, key] = pair.split(':').map((part) => part.trim());
        if (attribute && key) element.setAttribute(attribute, this.t(key));
      }
    }
  }

  /** Fills every `[data-language-switcher]` element with one button per language. */
  renderSwitchers(root = document) {
    for (const container of root.querySelectorAll('[data-language-switcher]')) {
      container.setAttribute('role', 'group');
      container.setAttribute('aria-label', this.t('language.label'));
      container.innerHTML = '';
      for (const choice of InterfaceLanguage.CHOICES) {
        const button = document.createElement('button');
        button.type = 'button';
        button.className = 'language-option';
        // The flag is decoration: the button is still named by its code, which
        // narrow screens hide from sight but not from screen readers.
        button.innerHTML = `<span class="language-flag" aria-hidden="true">${flagImage(choice.flag)}</span>` +
          `<span class="language-code">${choice.label}</span>`;
        button.title = choice.name;
        button.lang = choice.code;
        button.setAttribute('aria-pressed', String(choice.code === this.code));
        button.addEventListener('click', () => this.switchTo(choice.code));
        container.appendChild(button);
      }
    }
  }

  /**
   * Remembers `code` and reloads the page in it.
   *
   * A reload redraws everything a script has already written — status lines,
   * lists, answer cards — rather than tracking each of them for a later repaint.
   */
  switchTo(code) {
    if (code === this.code) return;
    try {
      window.localStorage.setItem(InterfaceLanguage.STORAGE_KEY, code);
    } catch {
      // Blocked storage: the reload below still shows the page, in the old language.
    }
    window.dispatchEvent(new CustomEvent('interface-language-change', { detail: { code } }));
    window.location.reload();
  }

  /** The language chosen before, else the browser's, else Indonesian. */
  #initialCode() {
    try {
      const stored = window.localStorage.getItem(InterfaceLanguage.STORAGE_KEY);
      if (stored && this.texts[stored]) return stored;
    } catch {
      // Private browsing or blocked storage: fall back to the browser language.
    }
    const browserCode = (navigator.language || '').slice(0, 2).toLowerCase();
    return this.texts[browserCode] ? browserCode : 'id';
  }
}

const interfaceLanguage = new InterfaceLanguage(INTERFACE_TEXTS);

/** Shorthand used throughout the page scripts. */
function t(key, values) {
  return interfaceLanguage.t(key, values);
}
